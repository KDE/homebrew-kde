require_relative "../lib/cmake"

class Kidletime < Formula
  desc "Monitoring user activity"
  homepage "https://api.kde.org/frameworks/kidletime/html/index.html"
  url "https://download.kde.org/stable/frameworks/6.7/kidletime-6.7.0.tar.xz"
  sha256 "60a6c70387b63e61147029ce57f170237271411630a3372a0e8d7240b8006aaf"
  head "https://invent.kde.org/frameworks/kidletime.git", branch: "master"

  depends_on "cmake" => [:build, :test]
  depends_on "doxygen" => :build
  depends_on "extra-cmake-modules" => [:build, :test]
  depends_on "graphviz" => :build
  depends_on "ninja" => :build

  depends_on "qt@6"

  def install
    system "cmake", *kde_cmake_args
    system "cmake", "--build", "build"
    system "cmake", "--install", "build"
    prefix.install "build/install_manifest.txt"
  end

  test do
    (testpath/"CMakeLists.txt").write("find_package(KF6IdleTime REQUIRED)")
    system "cmake", ".", "-Wno-dev"
  end
end
