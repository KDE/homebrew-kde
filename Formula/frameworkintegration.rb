require_relative "../lib/cmake"

class Frameworkintegration < Formula
  desc "Integration of Qt application with KDE workspaces"
  homepage "https://api.kde.org/frameworks/frameworkintegration/html/index.html"
  url "https://download.kde.org/stable/frameworks/6.7/frameworkintegration-6.7.0.tar.xz"
  sha256 "890101854bbbb3937d321f2ac35b2a0a8f3ce833422297ddda59bda8c8cac69d"
  head "https://invent.kde.org/frameworks/frameworkintegration.git", branch: "master"

  depends_on "cmake" => [:build, :test]
  depends_on "extra-cmake-modules" => [:build, :test]
  depends_on "ninja" => :build

  depends_on "kde-mac/kde/knewstuff"
  depends_on "kde-mac/kde/kpackage"

  def install
    system "cmake", *kde_cmake_args
    system "cmake", "--build", "build"
    system "cmake", "--install", "build"
    prefix.install "build/install_manifest.txt"
  end

  def caveats
    <<~EOS
      You need to take some manual steps in order to make this formula work:
        "$(brew --repo kde-mac/kde)/tools/do-caveats.sh"
    EOS
  end

  test do
    (testpath/"CMakeLists.txt").write("find_package(KF6FrameworkIntegration REQUIRED)")
    system "cmake", ".", "-Wno-dev"
  end
end
